def logger_debug(msg: str) -> None:
    """Emit a low-cardinality debug event.

    This is intentionally a module-level function that lazily imports
    the ``logging`` module to avoid import-time side effects in the
    pure domain.
    """
    import logging
    logging.getLogger(__name__).debug(msg)
