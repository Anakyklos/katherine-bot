@dataclass(frozen=True)
class ChatMessage:
    """A single persisted history message.

    ``role``
        Exactly ``"user"`` or ``"assistant"``.  ``"system"`` is rejected.

    ``content``
        The message text, a non‑empty string.

    ``source_id``
        Internal opaque local reference (e.g. ``"msg-1"``).  Never a
        real database UUID, user ID, or chat log ID.

    ``sort_key``
        Stable ordering tuple.  Must produce a total order consistent
        with the persisted record order — typically ``(created_at, id)``
        or equivalent.  Never only the timestamp.
    """

    role: str
    content: str
    source_id: str
    sort_key: tuple

    def __post_init__(self) -> None:
        # Validate role
        if self.role not in VALID_HISTORY_ROLES:
            raise TrustedContextError("invalid_history_role")

        # Validate content — non-empty after strip
        if not isinstance(self.content, str):
            raise TrustedContextError("invalid_history_content_type")
        if not self.content.strip():
            raise TrustedContextError("invalid_history_content")

        # Validate source_id — must be unique non-empty string
        if isinstance(self.source_id, bool):
            raise TrustedContextError("invalid_source_id_bool")
        if not isinstance(self.source_id, str) or not self.source_id:
            raise TrustedContextError("invalid_source_id")

        # Validate sort_key
        if not isinstance(self.sort_key, tuple):
            raise TrustedContextError("invalid_sort_key")
        if len(self.sort_key) < 2:
            # Must have at least (timestamp, id) for stable ordering
            raise TrustedContextError("invalid_sort_key")
        # Validate all components are comparable (no non-sortable types)
        for comp in self.sort_key:
            if isinstance(comp, bool):
                raise TrustedContextError("invalid_sort_key_component_bool")
            if isinstance(comp, (list, dict)):
                raise TrustedContextError("invalid_sort_key_component_container")


@dataclass(frozen=True)
class ContextItem:
    """A single untrusted context entry (profile, memory, or persona).

    ``kind``
        One of ``"profile"``, ``"memory"``, or ``"persona"``.

    ``content``
        The text payload — always a non‑empty string.

    ``provenance``
        Must be a member of ``Provenance`` allowlist.

    ``confidence``
        Float in ``[0.0, 1.0]``.  Rejects ``bool``, ``None``, NaN,
        and infinity.  Never confused with retrieval similarity.

    ``epistemic_status``
        Must be a member of ``EpistemicStatus`` allowlist.

    ``source_id``
        Internal opaque local reference (e.g. ``"ctx-1"``).  Never
        a real database UUID.

    ``internal_id``
        Optional real database UUID for internal tracking only.  Empty
        string means the real ID is unknown or not yet wired.
        Never logged or sent to the provider.
    """

    kind: str
    content: str
    provenance: str
    confidence: float
    epistemic_status: str
    source_id: str
    internal_id: str = ""

    def __post_init__(self) -> None:
        # Validate kind
        if self.kind not in ("profile", "memory", "persona"):
            raise TrustedContextError("invalid_kind")

        # Validate content — non-empty after strip
        if not isinstance(self.content, str) or not self.content:
            raise TrustedContextError("invalid_item_content")
        if not self.content.strip():
            raise TrustedContextError("invalid_item_content_whitespace")

        # Validate provenance
        if not Provenance.is_valid(self.provenance):
            raise TrustedContextError("invalid_provenance")

        # Validate epistemic_status
        if not EpistemicStatus.is_valid(self.epistemic_status):
            raise TrustedContextError("invalid_epistemic_status")

        # Validate confidence — strict checks
        if isinstance(self.confidence, bool):
            raise TrustedContextError("invalid_confidence_bool")
        if self.confidence is None:
            raise TrustedContextError("invalid_confidence_none")
        if not isinstance(self.confidence, (int, float)):
            raise TrustedContextError("invalid_confidence_type")
        if math.isnan(self.confidence) or math.isinf(self.confidence):
            raise TrustedContextError("invalid_confidence_nan_inf")
        if not (0.0 <= self.confidence <= 1.0):
            raise TrustedContextError("invalid_confidence_range")

        # Validate source_id — must be non-empty string, not bool
        if isinstance(self.source_id, bool):
            raise TrustedContextError("invalid_source_id_bool")
        if not isinstance(self.source_id, str) or not self.source_id:
            raise TrustedContextError("invalid_source_id")

        # Validate internal_id if present
        if self.internal_id and not isinstance(self.internal_id, str):
            raise TrustedContextError("invalid_internal_id_type")

    def to_json_dict(self) -> dict:
        """Return a JSON‑safe dict for the untrusted context payload.

        The ``source_id`` is **not** included in the JSON payload sent
        to the provider — only opaque local references are used.
        """
        return {
            "record_type": UNTRUSTED_CONTEXT_MARKER,
            "reference": self.source_id,
            "kind": self.kind,
            "provenance": self.provenance,
            "confidence": self.confidence,
            "epistemic_status": self.epistemic_status,
            "content": self.content,
        }


@dataclass(frozen=True)
class TruncationReport:
    """Report of pruning / truncation decisions.

    ``codes``
        Tuple of low‑cardinality event codes.  Examples:
        ``"history_partial"``, ``"memory_omitted"``, ``"profile_omitted"``.

    ``omitted_history_count``
        Number of history messages omitted due to budget.

    ``omitted_memory_count``
        Number of memory items omitted.

    ``omitted_profile_count``
        Number of profile items omitted.

    ``omitted_persona_count``
        Number of persona items omitted.

    ``selected_history_count``
        Number of history messages included.

    ``selected_memory_count``
        Number of memory items included.

    ``selected_profile_count``
        Number of profile items included.

    ``selected_persona_count``
        Number of persona items included.
    """

    codes: tuple[str, ...] = ()
    omitted_history_count: int = 0
    omitted_memory_count: int = 0
    omitted_profile_count: int = 0
    omitted_persona_count: int = 0
    selected_history_count: int = 0
    selected_memory_count: int = 0
    selected_profile_count: int = 0
    selected_persona_count: int = 0


@dataclass(frozen=True)
class LoadedContextData:
    """Raw loaded data from infrastructure before envelope construction.

    This is the single payload produced during the ``load_context`` stage.
    It holds the raw rows and snapshots that will later be converted into
    a ``ContextBundle`` via pure domain logic (no I/O).

    ``history_rows``
        List of raw history dicts with ``role``, ``content``, and ``id`` keys.

    ``retrieved_memories``
        List of ``RetrievedMemory`` objects from the RPC call.
        Imported lazily to keep this module infrastructure-free.

    ``profile_snapshot``
        Raw user profile dict (may be empty).

    ``persona_snapshot``
        Raw persona config string (may be empty).
    """

    history_rows: tuple = ()
    retrieved_memories: tuple = ()
    profile_snapshot: dict = field(default_factory=dict)
    persona_snapshot: str = ""


@dataclass(frozen=True)
class ContextBundle:
    """Separated context sections before envelope construction.

    ``trusted_policy``
        The system message content — only application‑controlled policy.
        Never contains history, profile, memory, or persona content.

    ``history``
        Tuple of ``ChatMessage`` in chronological order (oldest first).

    ``profile_items``
        Tuple of ``ContextItem`` entries derived from user profile.

    ``memory_items``
        Tuple of ``ContextItem`` entries derived from approved memories.

    ``persona_items``
        Tuple of ``ContextItem`` entries derived from legacy persona.

    ``truncation_report``
        Report of any pruning decisions already made during bundle
        construction (from the database / retrieval layer).
    """

    trusted_policy: str
    history: tuple[ChatMessage, ...] = ()
    profile_items: tuple[ContextItem, ...] = ()
    memory_items: tuple[ContextItem, ...] = ()
    persona_items: tuple[ContextItem, ...] = ()
    truncation_report: TruncationReport = field(default_factory=TruncationReport)


@dataclass(frozen=True)
class ContextBuildResult:
    """Result of envelope construction via ``build_envelope()``.

    ``messages``
        Final messages list ready for provider input.  The list is
        validated and fits within budget.

    ``source_map``
        Internal mapping from opaque local reference to actual
        source ID (for tracking purposes only — never logged or
        sent to the provider).

    ``truncation_report``
        Aggregated truncation report from pruning decisions.

    ``unit_count``
        Estimated input units of the final messages list.
    """

    messages: list
    source_map: dict[str, str] = field(default_factory=dict)
    truncation_report: TruncationReport = field(default_factory=TruncationReport)
    unit_count: int = 0


# ---------------------------------------------------------------------------
# Canonical JSON serialization helpers
# ---------------------------------------------------------------------------


def _serialize_canonical_json(value: Any) -> str:
    """Serialize *value* to canonical JSON.

    Uses ``ensure_ascii=False``, ``sort_keys=True``, and compact
    separators.  Raises ``TrustedContextError`` on non‑serialisable input.
    """
    try:
        return json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        )
    except (TypeError, ValueError):
        raise TrustedContextError("serialization_failed")


def _serialize_untrusted_items(items: tuple[ContextItem, ...]) -> str:
    """Serialize a tuple of ``ContextItem`` to canonical JSON.

    Returns the JSON representation of a list of item dicts.
    Returns ``""`` if *items* is empty.
    """
    if not items:
        return ""
    item_dicts = [item.to_json_dict() for item in items]
    return _serialize_canonical_json(item_dicts)


# ---------------------------------------------------------------------------
# Budget estimation for messages list
# ---------------------------------------------------------------------------


def _estimate_messages_units(messages: list) -> int:
    """Estimate the input units of a messages list.

    Uses the same canonical JSON serialization as
    ``estimate_provider_input_units``.
    """
    text = _serialize_canonical_json(messages)
    return max(1, len(text.encode("utf-8")))


# ---------------------------------------------------------------------------
# Bundle builder — pure conversion from loaded data
# ---------------------------------------------------------------------------


def build_context_bundle(
    trusted_policy: str,
    loaded_data: LoadedContextData,
) -> ContextBundle:
    """Convert ``LoadedContextData`` into a ``ContextBundle``.

    This is a pure-domain function that performs NO I/O — it only converts
    already-loaded raw data into typed ``ChatMessage`` and ``ContextItem``
    instances.

    ``trusted_policy``
        The trusted system prompt content (built by the engine after
        emotional transition).

    ``loaded_data``
        The ``LoadedContextData`` produced during ``load_context``.
    """
    # Convert history rows to ChatMessages
    chat_messages: list[ChatMessage] = []
    for i, msg in enumerate(loaded_data.history_rows):
        source_ref = f"msg-{i + 1}"
        chat_messages.append(ChatMessage(
            role=msg["role"],
            content=msg["content"],
            source_id=source_ref,
            sort_key=(msg.get("id", 0), i),
        ))

    # Convert retrieved memories to ContextItems
    memory_items: list[ContextItem] = []
    for j, mem in enumerate(loaded_data.retrieved_memories):
        source_ref = f"mem-{j + 1}"
        memory_items.append(mem.to_context_item(source_ref))

    # Profile as ContextItem
    profile_items: list[ContextItem] = []
    raw_profile = loaded_data.profile_snapshot
    if raw_profile and isinstance(raw_profile, dict):
        try:
            profile_str = json.dumps(
                raw_profile, ensure_ascii=False, sort_keys=True, separators=(",", ":")
            )
            profile_items.append(ContextItem(
                kind="profile",
                content=profile_str,
                provenance=Provenance.LEGACY_PROFILE,
                confidence=0.3,
                epistemic_status=EpistemicStatus.UNKNOWN,
                source_id="profile-1",
            ))
        except (TypeError, ValueError):
            pass

    # Persona as ContextItem
    persona_items: list[ContextItem] = []
    raw_persona = loaded_data.persona_snapshot
    if raw_persona and isinstance(raw_persona, str) and raw_persona.strip():
        persona_items.append(ContextItem(
            kind="persona",
            content=raw_persona.strip(),
            provenance=Provenance.LEGACY_PERSONA,
            confidence=0.3,
            epistemic_status=EpistemicStatus.UNKNOWN,
            source_id="persona-1",
        ))

    return ContextBundle(
        trusted_policy=trusted_policy,
        history=tuple(chat_messages),
        memory_items=tuple(memory_items),
        profile_items=tuple(profile_items),
        persona_items=tuple(persona_items),
    )


