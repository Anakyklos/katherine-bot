"""
Pure-domain module for trusted context boundaries.

This module defines the typed, deterministic boundary between:

* trusted application policy (system message)
* persisted history (user/assistant roles preserved)
* profile items (untrusted data)
* memory items (untrusted data with explicit approval)
* persona legacy items (untrusted data)
* current user message (byte‑identical, always last)

It depends only on the Python standard library and on
``backend.admission_contracts`` (for the 16 000‑unit constant).  It must
be importable without:

- FastAPI or Pydantic
- Groq SDK
- Supabase / PostgREST
- sentence_transformers
- ConversationEngine, memory, or engine
- environment variables
- network or filesystem access
- clock or randomness

Usage::

    from backend.trusted_context import (
        ChatMessage,
        ContextItem,
        ContextBundle,
        TruncationReport,
        ContextBuildResult,
        build_envelope,
        EpistemicStatus,
        Provenance,
    )

    bundle = ContextBundle(
        trusted_policy=system_policy,
        history=[ChatMessage(role="user", content="Hi", ...), ...],
        profile_items=[ContextItem(...), ...],
        memory_items=[ContextItem(...), ...],
    )
    result = build_envelope(bundle, user_message="Hello!")
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass, field
from typing import Any

from .admission_contracts import PROVIDER_INPUT_MAX_ESTIMATED_UNITS


# ---------------------------------------------------------------------------
# Constants — low‑cardinality allowlists
# ---------------------------------------------------------------------------

VALID_HISTORY_ROLES: frozenset = frozenset({"user", "assistant"})
"""Valid roles for persisted history messages — ``system`` is intentionally excluded."""

VALID_MESSAGE_ROLES: frozenset = frozenset({"system", "user", "assistant"})
"""Valid roles for final provider messages."""

UNTRUSTED_CONTEXT_MARKER = "untrusted_context"
"""Constant record_type marker for untrusted context payload."""


# ---------------------------------------------------------------------------
# Epistemic status — explicit allowlist
# ---------------------------------------------------------------------------

class EpistemicStatus:
    """Allowlisted epistemic status values for context items.

    Each value distinguishes the reliability / origin of a piece of
    information without conflating confidence scoring with provenance.

    Values:
        UNKNOWN — information not verified; default for legacy data.
        SELF_REPORT — user stated this about themselves.
        THIRD_PARTY — citation or report from someone else.
        FICTION — roleplay, hypothetical, or fictional scenario.
        INFERRED — derived by the system (e.g. from profile keys).
        APPROVED — confirmed through an explicit approval mechanism.
    """

    UNKNOWN = "unknown"
    SELF_REPORT = "self_report"
    THIRD_PARTY = "third_party"
    FICTION = "fiction"
    INFERRED = "inferred"
    APPROVED = "approved"

    _ALLOWLIST: frozenset = frozenset({
        UNKNOWN, SELF_REPORT, THIRD_PARTY, FICTION, INFERRED, APPROVED,
    })

    @classmethod
    def is_valid(cls, value: object) -> bool:
        """Return ``True`` if *value* is a valid epistemic status."""
        return value in cls._ALLOWLIST


# ---------------------------------------------------------------------------
# Provenance — explicit allowlist
# ---------------------------------------------------------------------------

class Provenance:
    """Allowlisted provenance values for context items.

    Values:
        LEGACY_PROFILE — from the legacy ``user_profile`` JSON snapshot.
        USER_CONFIRMED — explicitly confirmed by the user.
        EXTRACTION — extracted by an archival extraction pipeline.
        SYSTEM — generated by the system (e.g. emotional state).
        LEGACY_MEMORY — from the legacy memories store without full contract.
        LEGACY_PERSONA — from the legacy ``persona_config`` field.
    """

    LEGACY_PROFILE = "legacy_profile_snapshot"
    USER_CONFIRMED = "user_confirmed"
    EXTRACTION = "extraction"
    SYSTEM = "system"
    LEGACY_MEMORY = "legacy_memory"
    LEGACY_PERSONA = "legacy_persona"

    _ALLOWLIST: frozenset = frozenset({
        LEGACY_PROFILE, USER_CONFIRMED, EXTRACTION, SYSTEM,
        LEGACY_MEMORY, LEGACY_PERSONA,
    })

    @classmethod
    def is_valid(cls, value: object) -> bool:
        """Return ``True`` if *value* is a valid provenance."""
        return value in cls._ALLOWLIST


# ---------------------------------------------------------------------------
# Typed errors
# ---------------------------------------------------------------------------

class TrustedContextError(Exception):
    """Validation failure for trusted context construction.

    Carries only a structured code — never exposes raw content, prompts,
    UUIDs, users, IP addresses, HMACs, or secrets in ``str()``, ``repr()``,
    or public attributes.
    """

    def __init__(self, code: str) -> None:
        self.code = code
        super().__init__(code)

    def __str__(self) -> str:
        return self.code

    def __repr__(self) -> str:
        return f"TrustedContextError(code={self.code!r})"


